// Social Brand Button
export function SocialBrandButton({ platform, url, onClick, disabled = false, asIcon = false, className = '', cardStyle = 'glass' }) {
  if (!url && !asIcon) return null;

  const key = (platform || '').toLowerCase().trim();
  const brand = BRAND_SVGS[key] || {
    color: '#ffffff',
    glow: 'rgba(255, 255, 255, 0.5)',
    name: platform || 'Link',
    svg: (
      <svg viewBox="0 0 24 24" className="w-5 h-5 fill-current">
        <circle cx="12" cy="12" r="10" />
      </svg>
    )
  };

  if (asIcon) {
    return (
      <span className="flex items-center justify-center shrink-0" style={{ color: brand.color }}>
        {brand.svg}
      </span>
    );
  }

  const bgClasses = cardStyle === 'transparent'
    ? 'bg-transparent hover:bg-white/10 border-white/15 shadow-none'
    : cardStyle === 'ultra_glass'
    ? 'bg-black/15 hover:bg-black/30 border-white/10 backdrop-blur-md shadow-sm'
    : cardStyle === 'dark'
    ? 'bg-black/85 hover:bg-black/95 border-white/20 backdrop-blur-3xl shadow-lg'
    : 'bg-black/50 hover:bg-black/80 border-white/15 hover:border-white/40 backdrop-blur-2xl shadow-[0_4px_16px_rgba(0,0,0,0.6)]';

  return (
    <a
      href={disabled ? '#' : url}
      target={disabled ? '_self' : '_blank'}
      rel="noopener noreferrer"
      onClick={onClick}
      className={`group relative w-10 h-10 sm:w-11 sm:h-11 rounded-2xl border flex items-center justify-center transition-all duration-300 ${bgClasses} ${disabled ? 'cursor-default' : 'hover:scale-110 active:scale-95 cursor-pointer'} text-white/80 hover:text-white ${className}`}
      title={brand.name}
    >
      {/* Brand glow on hover */}
      {!disabled && (
        <div 
          className="absolute inset-0 rounded-2xl opacity-0 group-hover:opacity-100 transition-opacity duration-300 blur-md pointer-events-none"
          style={{ backgroundColor: brand.glow }}
        />
      )}
      <div className="relative z-10 text-white/85 group-hover:text-white transition-transform duration-300 group-hover:scale-110 flex items-center justify-center">
        {brand.svg}
      </div>
    </a>
  );
}
